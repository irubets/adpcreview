library(adpcreview)
old <- getwd()
scratch <- tempfile("review-package-")
dir.create(scratch)
setwd(scratch)
app <- create_app(output_dir = file.path(scratch, "visualizations"))
stopifnot(inherits(app, "shiny.appobj"), identical(getwd(), normalizePath(scratch, winslash = "/")))
shiny::testServer(app$serverFuncSource(), { session$flushReact() })
app2 <- create_app()
stopifnot(inherits(app2, "shiny.appobj"))
invalid <- try(create_app(output_dir = NA_character_), silent = TRUE)
stopifnot(inherits(invalid, "try-error"))
resources <- list.files(system.file("app", package = "adpcreview"), recursive = TRUE, all.files = TRUE)
stopifnot(!any(grepl("[.](xpt|sas7bdat|csv|xlsx|zip|rds|RData)$|Renviron|^Examples/", resources, ignore.case = TRUE)))
setwd(old)
unlink(scratch, recursive = TRUE)
